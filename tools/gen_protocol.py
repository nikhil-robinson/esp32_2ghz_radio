#!/usr/bin/env python3
"""Generate the C headers and the protocol reference from host/esp_sdr/protocol.py.

  components/esp_sdr/include/esp_sdr_record.h  stream records (library)
  firmware/main/protocol.h                       requests / responses (firmware)
  docs/protocol.md                               protocol reference

Usage: python3 tools/gen_protocol.py [--check]
--check exits non-zero when a checked-in header is out of date.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'host'))
from esp_sdr import protocol as p  # noqa: E402

RECORD_HEADER = ROOT / 'components/esp_sdr/include/esp_sdr_record.h'
PROTOCOL_DOC = ROOT / 'docs/protocol.md'
PROTOCOL_HEADER = ROOT / 'firmware/main/protocol.h'
BANNER = '/* Generated by tools/gen_protocol.py from host/esp_sdr/protocol.py. Do not edit. */\n'


def enum(name, rows):
    body = ''.join(f'    {k} = {v},\n' for k, v in rows)
    return f'typedef enum {{\n{body}}} {name};\n\n'


def message_struct(m, prefix):
    if not m.fields:
        return ''
    fields = ''.join(f'    {t} {n};\n' for n, t in m.fields)
    tag = f'{prefix}{m.name.lower()}_t'
    return (f'/** {m.doc} */\ntypedef struct __attribute__((packed)) {{\n{fields}}} {tag};\n'
            f'_Static_assert(sizeof({tag}) == {m.size}, "{m.name} layout");\n\n')


def record_header():
    out = [BANNER,
           '/*\n * Self-describing stream records written by esp_sdr_run() to the sink:\n *\n'
           ' *   magic u16 | type u8 | tag u8 | length u32 | payload | crc32\n *\n'
           ' * crc32 (IEEE, zlib) covers type .. payload. `tag` echoes esp_sdr_run_config_t.tag.\n */\n',
           '#pragma once\n\n#include <stdint.h>\n\n',
           f'#define ESP_SDR_RECORD_MAGIC 0x{p.MAGIC:04X}u\n',
           f'#define ESP_SDR_RECORD_HEADER_SIZE {p.HEADER_SIZE}u\n',
           f'#define ESP_SDR_RECORD_CRC_SIZE {p.CRC_SIZE}u\n\n',
           'typedef struct __attribute__((packed)) {\n    uint16_t magic;\n    uint8_t type;\n'
           '    uint8_t tag;\n    uint32_t length;\n} esp_sdr_record_header_t;\n'
           '_Static_assert(sizeof(esp_sdr_record_header_t) == ESP_SDR_RECORD_HEADER_SIZE, "record header");\n\n',
           enum('esp_sdr_record_type_t', [(f'ESP_SDR_RECORD_{m.name}', f'0x{m.id:02X}') for m in p.RECORDS])]
    out += [message_struct(m, 'esp_sdr_record_') for m in p.RECORDS]
    return ''.join(out).rstrip('\n') + '\n'


def protocol_header():
    out = [BANNER,
           '/* Firmware request / response frames: same layout as esp_sdr_record.h records. */\n',
           '#pragma once\n\n#include <stdint.h>\n#include "esp_sdr_record.h"\n\n',
           f'#define PROTOCOL_VERSION {p.PROTOCOL_VERSION}u\n',
           f'#define PROTOCOL_MAX_REQUEST_PAYLOAD {p.MAX_REQUEST_PAYLOAD}u\n\n',
           enum('message_type_t', [(f'REQ_{m.name}', f'0x{m.id:02X}') for m in p.REQUESTS] +
                [(f'RSP_{m.name}', f'0x{m.id:02X}') for m in p.RESPONSES])]
    for name, table in (('wire_rate_t', p.RATES), ('wire_format_t', p.FORMATS), ('wire_workers_t', p.WORKERS),
                        ('wire_gpio_t', p.GPIO_STATES), ('wire_run_status_t', p.RUN_STATUS),
                        ('wire_error_t', p.ERRORS), ('wire_mode_t', p.MODES),
                        ('wire_region_t', p.REGIONS)):
        out.append(enum(name, [(f'WIRE_{k}', v) for k, v in table.items()]))
    out += [message_struct(m, 'msg_') for m in p.REQUESTS + p.RESPONSES]
    return ''.join(out).rstrip('\n') + '\n'


def protocol_doc():
    def table(messages):
        rows = ['| Name | Id | Payload fields | Meaning |', '|---|---|---|---|']
        for m in messages:
            fields = ', '.join(f'`{n}` {t.replace("_t", "")}' for n, t in m.fields if not n.startswith('reserved'))
            rows.append(f'| `{m.name}` | `0x{m.id:02X}` | {fields or "-"} | {m.doc} |')
        return '\n'.join(rows) + '\n'

    def values(table_):
        return ', '.join(f'{k.lower()} = {v}' for k, v in table_.items())

    return f'''<!-- Generated by tools/gen_protocol.py from host/esp_sdr/protocol.py. Do not edit. -->
# ESP-SDR wire protocol (version {p.PROTOCOL_VERSION})

Every frame, in both directions and for stream records, has the same layout
(little endian):

| Field | Size | Notes |
|---|---|---|
| magic | 2 | `E5 D5` |
| type | 1 | message id below |
| seq / tag | 1 | requests: chosen by the host; replies and records echo it |
| length | 4 | payload bytes |
| payload | length | fixed fields below, then variable data where noted |
| crc32 | 4 | IEEE CRC-32 (zlib) over type, seq, length and payload |

Rules:

* Requests marked "followed by" carry variable data after the fixed fields.
* Requests carry at most {p.MAX_REQUEST_PAYLOAD} payload bytes; longer ones are answered with `ERR_BAD_LENGTH`.
* A request with a bad CRC is ignored; the host times out and retries.
* Every request gets exactly one `ACK` or typed reply, except `CAPTURE`, `RING_*`,
  `SPECTRUM` and `IQ_STREAM`, which send data frames and always end with `RUN_DONE`.
* Any byte sent while a stream runs stops it (`STOP` is the polite form).
* Bytes before a magic are skipped, so boot output and noise are harmless.
* A request on a second port while the first holds the lease (5 s after its last
  request, or until `RELEASE`) is answered with `ERR_BUSY`.

Values: rate: {values(p.RATES)}; format: {values(p.FORMATS)}; workers: {values(p.WORKERS)};
GPIO state: {values(p.GPIO_STATES)}; mode: {values(p.MODES)}; region: {values(p.REGIONS)}.

Errors: {values(p.ERRORS)}.

Run status: {values(p.RUN_STATUS)}.

## Requests

{table(p.REQUESTS)}
## Replies

{table(p.RESPONSES)}
## Stream records (emitted by the library, `esp_sdr_record.h`)

{table(p.RECORDS)}
Spectrum bins are 0.5 dB codes (`db_step` codes per dB) relative to full scale of
the int16 FFT, in FFT order: bin k is k * fs / N above the LO for k < N/2, and
the upper half holds the negative frequencies (apply an fftshift to display). `flags`: bit 0 max-hold,
bit 1 some FFT work was abandoned, bit 2 frames were dropped before this one.
IQ frame `flags`: bit 0 gap before this frame, bit 1 frames dropped before it.
'''


if __name__ == '__main__':
    outputs = {RECORD_HEADER: record_header(), PROTOCOL_HEADER: protocol_header(), PROTOCOL_DOC: protocol_doc()}
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if '--check' in sys.argv:
        if stale:
            sys.exit('stale: ' + ', '.join(str(path.relative_to(ROOT)) for path in stale) +
                     ' - run tools/gen_protocol.py')
        sys.exit(0)
    for path in stale:
        path.write_text(outputs[path])
        print(f'wrote {path.relative_to(ROOT)}')
